'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const invoke = (ch, arg) => ipcRenderer.invoke(ch, arg);

contextBridge.exposeInMainWorld('polirec', {
    state: () => invoke('state'),
    addCourse: c => invoke('course:add', c),
    updateCourse: (id, patch) => invoke('course:update', { id, patch }),
    removeCourse: id => invoke('course:remove', id),
    reorderCourses: ids => invoke('course:reorder', ids),
    webeepCourses: () => invoke('webeep:courses'),
    sync: ids => invoke('sync', ids),
    stopSync: () => invoke('sync:stop'),
    transcribe: (courseId, keys) => invoke('transcribe', { courseId, keys }),
    cancelTranscriptions: () => invoke('transcribe:cancel'),
    notes: (courseId, key, template, provider) => invoke('notes', { courseId, key, template, provider }),
    notesBatch: (courseId, template, provider) => invoke('notes:batch', { courseId, template, provider }),
    agent: (courseId, prompt, provider) => invoke('agent', { courseId, prompt, provider }),
    recording: (courseId, key) => invoke('recording', { courseId, key }),
    saveSettings: s => invoke('settings:save', s),
    setAppearance: a => invoke('appearance', a),
    pickDir: def => invoke('pick-dir', def),
    open: (courseId, kind, file) => invoke('open', { courseId, kind, file }),
    openPath: p => invoke('open-path', p),
    openExternal: u => invoke('open-external', u),
    readFile: (courseId, kind, file) => invoke('read-file', { courseId, kind, file }),
    reveal: p => invoke('reveal', p),
    setupDetect: () => invoke('setup:detect'),
    setupInstall: rec => invoke('setup:install', rec),
    setupSkip: () => invoke('setup:skip'),
    hw: () => invoke('hw'),
    cloud: { detect: () => invoke('cloud:detect'), set: o => invoke('cloud:set', o), pull: () => invoke('cloud:pull') },
    integrations: { apps: () => invoke('integrations:apps'), testNotion: (token, parent) => invoke('integrations:testNotion', { token, parent }) },
    exportNote: (scope, file, target, html) => invoke('notes:exportTo', { scope, file, target, html }),
    search: {
        status: () => invoke('search:status'), ready: () => invoke('search:ready'), install: () => invoke('search:install'),
        query: (text, courseId, k) => invoke('search:query', { text, courseId, k }), ask: (question, courseId) => invoke('search:ask', { question, courseId }),
        index: courseId => invoke('search:index', courseId),
    },
    aiBackfill: ids => invoke('ai:backfill', ids),
    genCoursePage: id => invoke('course:genPage', id),
    setEngine: (engine, model) => invoke('engine:set', { engine, model }),
    ws: {
        get: courseId => invoke('ws:get', courseId),
        page: (courseId, text) => invoke('ws:page', { courseId, text }),
        addTodo: (courseId, todo) => invoke('ws:todo:add', { courseId, todo }),
        setTodo: (courseId, id, patch) => invoke('ws:todo:set', { courseId, id, patch }),
        removeTodo: (courseId, id) => invoke('ws:todo:remove', { courseId, id }),
        pomodoro: (courseId, minutes, kind, start) => invoke('ws:pomodoro', { courseId, minutes, kind, start }),
        allTodos: () => invoke('ws:all-todos'),
    },
    cal: {
        sync: () => invoke('cal:sync'),
        importText: t => invoke('cal:importText', t),
        importIcs: src => invoke('cal:importIcs', src),
        events: (from, to) => invoke('cal:events', { from, to }),
        revealIcs: () => invoke('cal:revealIcs'),
    },
    rooms: { spaces: () => invoke('rooms:spaces'), free: q => invoke('rooms:free', q), status: q => invoke('rooms:status', q), photo: id => invoke('rooms:photo', id) },
    notes: {
        scopes: () => invoke('notes:scopes'),
        list: scope => invoke('notes:list', scope),
        read: (scope, file) => invoke('notes:read', { scope, file }),
        write: (scope, file, content) => invoke('notes:write', { scope, file, content }),
        create: (scope, title, kind) => invoke('notes:create', { scope, title, kind }),
        rename: (scope, file, name) => invoke('notes:rename', { scope, file, name }),
        remove: (scope, file) => invoke('notes:remove', { scope, file }),
        asset: (scope, file, name, data) => invoke('notes:asset', { scope, file, name, data }),
        dir: scope => invoke('notes:dir', scope),
        engines: () => invoke('notes:engines'),
        installEngine: n => invoke('notes:installEngine', n),
        compile: (scope, file) => invoke('notes:compile', { scope, file }),
        exportPdf: (html, out) => invoke('notes:exportPdf', { html, out }),
    },
    assist: q => invoke('ai:assist', q),
    dictate: (data, language) => invoke('dictate', { data, language }),
    cleanTranscripts: (courseId, keys, restore) => invoke('transcripts:clean', { courseId, keys, restore }),
    about: () => invoke('about'),
    notice: () => invoke('about:notice'),
    checkUpdate: () => invoke('update:check'),
    on: cb => ipcRenderer.on('evt', (_, e) => cb(e)),
});
